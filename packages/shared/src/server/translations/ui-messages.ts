export type UiMessageKey = keyof typeof uiMessages;
export const uiMessageKeys = Object.keys(uiMessages) as UiMessageKey[];

/** Khóa chữ cố định luôn bắt đầu bằng "ui." khi lưu cùng bản dịch nội dung (khóa nội dung là mã băm 16 ký tự thập lục phân). */
export const uiKeyPrefix = "ui.";
export const storedUiKey = (key: UiMessageKey) => `${uiKeyPrefix}${key}`;
export const uiStoredKeyPattern = /^ui\.[A-Za-z0-9_.-]{1,120}$/;

export function isUiMessageKey(value: string): value is UiMessageKey {
  return Object.hasOwn(uiMessages, value);
}

/** Tên các chỗ chèn biến ({ten}) trong một câu, theo thứ tự xuất hiện và không lặp. */
export function messagePlaceholders(text: string): string[] {
  return [...new Set([...text.matchAll(/\{([A-Za-z0-9_]+)\}/g)].map((match) => match[1]))];
}

/** Thay {ten} bằng giá trị; biến không có trong `vars` giữ nguyên để lỗi hiện rõ thay vì mất chữ. */
export function formatMessage(template: string, vars?: Record<string, string | number>): string {
  if (!vars) return template;
  return template.replace(/\{([A-Za-z0-9_]+)\}/g, (whole, name: string) => Object.hasOwn(vars, name) ? String(vars[name]) : whole);
}
